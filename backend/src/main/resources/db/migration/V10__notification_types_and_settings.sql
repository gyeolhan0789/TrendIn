-- 관심 키워드별 이전 트렌드 유형을 보존해 유형 진입·이탈·전환을 감지한다.
ALTER TABLE member_interest_keywords
    ADD COLUMN previous_trend_types varchar(255)[];

-- null은 아직 기준 상태를 잡지 않은 기존/신규 관심 키워드를 뜻한다.
-- 첫 스케줄 실행에서 실제 최신 keyword_metrics를 기준으로 채워 오탐을 막는다.

CREATE TABLE notification_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    keyword_surge_enabled boolean DEFAULT true NOT NULL,
    keyword_drop_enabled boolean DEFAULT true NOT NULL,
    new_trend_enabled boolean DEFAULT true NOT NULL,
    trend_turning_point_enabled boolean DEFAULT true NOT NULL,
    CONSTRAINT uk_notification_settings_member UNIQUE (member_id),
    CONSTRAINT fk_notification_settings_member
        FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE
);

ALTER TABLE notifications DROP CONSTRAINT ck_notifications_type;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_type CHECK (
    notification_type IN (
        'TREND_CHANGE', 'KEYWORD_SURGE', 'KEYWORD_DROP',
        'NEW_TREND', 'TREND_TURNING_POINT'
    )
);
