-- Add the country axis to the daily mention counts.
--
-- The existing metric tables split on time only: keyword_metrics is unique per
-- (keyword_id, period) and keyword_metric_history per (keyword_id,
-- bucket_start). Neither can answer "how often did this keyword appear in
-- France yesterday", and widening them would force every existing reader to
-- start summing over countries. The country breakdown lives in its own table
-- and the existing tables keep reporting the all-country total.
--
-- metric_date is the KST calendar day. The pipeline already cuts its daily
-- buckets on KST, so storing a local calendar day here would leave the service
-- with two different notions of "a day". Local-date display, if it is ever
-- wanted, is a conversion in the query layer.
--
-- country_code is ISO 3166-1 alpha-2, held as varchar rather than char because
-- char blank-pads on PostgreSQL and the padding then leaks into equality
-- comparisons. The CHECK, rather than an enum, follows keywords.domain: adding
-- a country should not need a migration.
--
-- The table is empty until the pipeline learns where an article comes from.
-- Nothing upstream carries a country today: the collected article envelope has
-- domain, source, route, url and author, normalization adds lang, and lang is
-- not a country. Creating the table first fixes the code, the date basis and
-- the deduplication key so the pipeline and the query layer can be built
-- against the same contract instead of against each other's assumptions.

CREATE TABLE keyword_country_daily_metrics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id bigint NOT NULL,
    country_code varchar(2) NOT NULL,
    metric_date date NOT NULL,
    mention_count bigint NOT NULL,
    CONSTRAINT uk_keyword_country_daily_metrics
        UNIQUE (keyword_id, metric_date, country_code),
    CONSTRAINT ck_keyword_country_daily_metrics_country_code
        CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_keyword_country_daily_metrics_mention_count
        CHECK (mention_count >= 0),
    CONSTRAINT fk_keyword_country_daily_metrics_keyword
        FOREIGN KEY (keyword_id) REFERENCES keywords (id)
);

-- "Top keywords in this country on this date" cannot use the unique index,
-- whose leading column is keyword_id.
CREATE INDEX ix_keyword_country_daily_metrics_date
    ON keyword_country_daily_metrics (metric_date, country_code);
