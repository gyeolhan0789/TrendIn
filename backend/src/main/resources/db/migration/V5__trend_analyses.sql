CREATE TABLE trend_analyses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trend_id bigint NOT NULL,
    period metric_period NOT NULL,
    trend_types varchar(255)[] NOT NULL,
    description varchar(255) NOT NULL,
    summary text,
    reason text,
    input_fingerprint varchar(64),
    analyzed_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_trend_analyses_trend_period UNIQUE (trend_id, period),
    CONSTRAINT fk_trend_analyses_trend
        FOREIGN KEY (trend_id) REFERENCES trends (id) ON DELETE CASCADE
);

-- 기존 기간 구분 없는 분석은 7D로 보존한다. fingerprint는 과거 입력을 알 수 없어 비워 둔다.
INSERT INTO trend_analyses (
    trend_id, period, trend_types, description, summary, reason, analyzed_at
)
SELECT id, '7D'::metric_period, trend_types, description, summary, reason, updated_at
  FROM trends
 WHERE description IS NOT NULL;

-- 분석 전에도 NEW/RISING/CURRENT 키워드의 대표 trends 행을 만들 수 있게 한다.
-- 기존 AI 필드는 현재 API와 저장 목록이 읽으므로 후속 API 전환 전까지 유지한다.
ALTER TABLE trends ALTER COLUMN description DROP NOT NULL;
