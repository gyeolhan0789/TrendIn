-- Let a member sign in through an external identity provider.
--
-- The provider link lives in its own table rather than as columns on members.
-- A member can hold at most one link per provider but may collect several over
-- time, and the spec already anticipates more providers than the one being
-- built now. Columns on members would mean a migration per provider and a row
-- full of nulls for everyone who never used one.
--
-- provider_user_id is the provider's own immutable identifier, not the email.
-- Emails on GitLab are editable, so matching on email would hand one person's
-- account to another as soon as they swapped addresses. The unique constraint
-- on (provider, provider_user_id) is what makes a repeat login find the same
-- member; the unique on (member_id, provider) stops one member from ending up
-- with two links to the same provider.
--
-- It is stored as varchar rather than bigint because providers disagree on the
-- shape of their identifiers: GitLab hands out integers, others hand out UUIDs
-- or opaque strings. Narrowing it later is a migration; widening it now is not.

CREATE TABLE member_oauth_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    provider varchar(30) NOT NULL,
    provider_user_id varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_member_oauth_accounts_provider_user
        UNIQUE (provider, provider_user_id),
    CONSTRAINT uk_member_oauth_accounts_member_provider
        UNIQUE (member_id, provider),
    CONSTRAINT fk_member_oauth_accounts_member
        FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE
);

-- A member who only ever signed in through a provider has no password to store.
-- The column stayed NOT NULL while every account was created by the email form;
-- an OAuth-only member cannot satisfy that, and inventing a random hash would
-- leave a credential nobody can use but an attacker could try to crack.
--
-- Nullable does not weaken the email login path: it compares the supplied
-- password against the stored hash and already treats a missing hash as a
-- failed match, so a password-less member cannot be signed in with a password.
ALTER TABLE members ALTER COLUMN password DROP NOT NULL;
