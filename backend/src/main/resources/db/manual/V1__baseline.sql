-- TrendIn service schema baseline for an empty PostgreSQL 17 database.
-- This file is applied manually. Flyway is not configured in this project.
-- It intentionally contains no DROP or TRUNCATE statements.

CREATE TYPE metric_period AS ENUM ('24H', '7D', '30D');
CREATE DOMAIN trend_type AS varchar(255)
    CHECK (VALUE IN ('CURRENT', 'RISING', 'NEW'));

CREATE TABLE members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL,
    password varchar(255) NOT NULL,
    nickname varchar(30) NOT NULL,
    onboarding_completed boolean DEFAULT false NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_members_email UNIQUE (email)
);

CREATE SEQUENCE member_domains_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE member_domains (
    id bigint NOT NULL PRIMARY KEY,
    member_id bigint NOT NULL,
    domain varchar(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT ux_member_domains_member_id_domain UNIQUE (member_id, domain),
    CONSTRAINT fk_member_domains_member
        FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE,
    CONSTRAINT ck_member_domains_domain CHECK (domain IN ('DEVELOP', 'FASHION'))
);

CREATE TABLE keywords (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    normalized_name varchar(255) NOT NULL,
    domain varchar(255) NOT NULL,
    CONSTRAINT uk_keywords_domain_normalized_name UNIQUE (domain, normalized_name),
    CONSTRAINT ck_keywords_domain CHECK (domain IN ('DEVELOP', 'FASHION'))
);

CREATE TABLE member_interest_keywords (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    keyword_id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    was_trending boolean DEFAULT false NOT NULL,
    CONSTRAINT uk_member_interest_keywords_member_keyword UNIQUE (member_id, keyword_id),
    CONSTRAINT fk_member_interest_keywords_member
        FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_member_interest_keywords_keyword
        FOREIGN KEY (keyword_id) REFERENCES keywords (id)
);

CREATE TABLE contents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    source varchar(255) NOT NULL,
    url varchar(255) NOT NULL,
    body_object_key text,
    published_at timestamp(6) with time zone NOT NULL,
    collected_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_contents_url UNIQUE (url)
);

CREATE TABLE keyword_contents (
    content_id bigint NOT NULL,
    keyword_id bigint NOT NULL,
    PRIMARY KEY (content_id, keyword_id),
    CONSTRAINT fk_keyword_contents_content
        FOREIGN KEY (content_id) REFERENCES contents (id),
    CONSTRAINT fk_keyword_contents_keyword
        FOREIGN KEY (keyword_id) REFERENCES keywords (id)
);

CREATE TABLE keyword_metrics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id bigint NOT NULL,
    period metric_period NOT NULL,
    period_start timestamp(6) with time zone NOT NULL,
    period_end timestamp(6) with time zone NOT NULL,
    mention_count bigint NOT NULL,
    previous_mention_count bigint NOT NULL,
    growth_amount bigint NOT NULL,
    growth_rate numeric(38, 2),
    mention_rank integer,
    CONSTRAINT uk_keyword_metrics_period
        UNIQUE (keyword_id, period, period_start, period_end),
    CONSTRAINT fk_keyword_metrics_keyword
        FOREIGN KEY (keyword_id) REFERENCES keywords (id)
);

CREATE TABLE keyword_metric_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id bigint NOT NULL,
    bucket_start timestamp(6) with time zone NOT NULL,
    bucket_end timestamp(6) with time zone NOT NULL,
    mention_count bigint NOT NULL,
    CONSTRAINT uk_keyword_metric_history_bucket
        UNIQUE (keyword_id, bucket_start, bucket_end),
    CONSTRAINT fk_keyword_metric_history_keyword
        FOREIGN KEY (keyword_id) REFERENCES keywords (id)
);

CREATE TABLE trends (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id bigint NOT NULL,
    trend_types varchar(255)[] NOT NULL,
    description varchar(255) NOT NULL,
    summary text,
    reason text,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_trends_keyword UNIQUE (keyword_id),
    CONSTRAINT fk_trends_keyword FOREIGN KEY (keyword_id) REFERENCES keywords (id)
);

CREATE TABLE keyword_relations (
    source_keyword_id bigint NOT NULL,
    target_keyword_id bigint NOT NULL,
    relation_score numeric(5, 2) NOT NULL,
    co_occurrence_count bigint NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    PRIMARY KEY (source_keyword_id, target_keyword_id),
    CONSTRAINT ck_keyword_relations_score CHECK (relation_score BETWEEN 0 AND 100),
    CONSTRAINT fk_keyword_relations_source
        FOREIGN KEY (source_keyword_id) REFERENCES keywords (id),
    CONSTRAINT fk_keyword_relations_target
        FOREIGN KEY (target_keyword_id) REFERENCES keywords (id)
);

CREATE TABLE saved_trends (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    trend_id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_saved_trends_member_trend UNIQUE (member_id, trend_id),
    CONSTRAINT fk_saved_trends_member
        FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_trends_trend
        FOREIGN KEY (trend_id) REFERENCES trends (id) ON DELETE RESTRICT
);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    trend_id bigint NOT NULL,
    notification_type varchar(30) NOT NULL,
    message varchar(255) NOT NULL,
    is_read boolean NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    dedup_key varchar(255) NOT NULL,
    CONSTRAINT uk_notifications_dedup_key UNIQUE (dedup_key),
    CONSTRAINT fk_notifications_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_notifications_trend FOREIGN KEY (trend_id) REFERENCES trends (id),
    CONSTRAINT ck_notifications_type CHECK (notification_type IN ('TREND_CHANGE'))
);
