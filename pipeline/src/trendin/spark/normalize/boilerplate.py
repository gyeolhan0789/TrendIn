r"""매체 상투 요소 제거 — 정제 단계 8 ([03 §4](../../../../spark/docs/03-normalization-spec.md)).

단계 2~7 이 **마크업**을 걷는다면 여기는 **기사 본문이 아닌 텍스트**를 걷는다. 태그를 지운
뒤에도 남는 것들이다 — 쇼핑 링크의 앵커 문구, 관련기사 위젯, 사진 크레딧, 번역 고지.

**왜 스코어링이 아니라 정제인가.** 2026-09-09 실측(fashion 373건)에서 이것들이 진짜 키워드보다
점수가 높았다:

```
자세히 보기   score 0.415  bm25 4.57   ← 쇼핑 링크 앵커
게티          score 0.354  bm25 4.88   ← 사진 크레딧
인스타그램    score 0.384  bm25 2.77   ← 캡션 크레딧 (출현 457회)
데님          score 0.325  bm25 1.65   ← 진짜 키워드
```

BM25 관점에서 이건 **모범적인 키워드**다 — 짧은 블록에 반복 등장하고 문서 수가 적당하다.
가중치를 어떻게 돌려도 안 내려간다. 노이즈 사전도 답이 아니다: [04 §5] 의 노이즈 규칙은
n-gram 의 **모든** 토큰이 사전에 있어야 버리므로 `게티 이미지` · `상품 자세히 보기` 같은
변형을 계속 놓친다. **본문에 들어오지 않게 하는 것이 유일한 처방이다.**

**규칙은 세 모양이다.**

| | 무엇 | 근거 |
| --- | --- | --- |
| 꼬리 절단 | `관련기사` 줄부터 끝까지 | 그 뒤는 관련기사 위젯이다 (61문서, 전부) |
| 줄 제거 | 줄 전체가 쇼핑 앵커 · 번역 고지 | `상품 자세히 보기`(26) · `구매하러 가기`(23) |
| 꼬리 자르기 | 줄 안의 크레딧 부분만 | `... \| 인스타그램 @moncler` → 앞부분만 남긴다 |

**셋째가 줄 제거가 아닌 이유** — 크레딧 줄의 앞부분은 캡션이고 거기에 브랜드명이 있다
(`반클리프 아펠 주얼리 | 인스타그램 @vancleefarpels`). 줄을 통째로 버리면 `반클리프 아펠` 이
함께 사라진다. 크레딧만 자르면 이름은 남고 `인스타그램` 은 없어진다.

**패턴을 코드에 두는 이유** — `text.py` 의 정규식과 같은 성격이다. 구조 패턴이라 사전 항목처럼
줄 단위로 늘어나지 않는다. 매체가 늘어 목록이 길어지면 `conf/` 로 옮긴다.

**⚠️ 이 목록은 fashion 7 매체를 보고 만들었다.** 소스가 늘면 그 매체의 상투 요소를 실측해서
추가한다 — 상위 100 후보 검수([04 §9])에서 드러난다. `hn` 은 본문이 없어 영향이 없다.

**pyspark 를 import 하지 않는다** ([09 §4] 층 1).
"""

from __future__ import annotations

import re

# --- 꼬리 절단 ---------------------------------------------------------------

# 이 줄부터 문서 끝까지 버린다. 기사 본문의 끝을 표시하는 위젯 제목이다 — 그 뒤로는
# 카테고리 · 다른 기사 제목 · `2026.08.31by 원예하` 같은 서명이 이어진다.
_CUT_FROM = re.compile(r"^(?:관련\s*기사|추천\s*기사|함께\s*보면\s*좋은\s*기사)$")

# --- 줄 제거 -----------------------------------------------------------------

# 줄 전체가 링크 앵커인 것. 쇼핑 링크가 상품명 다음 줄에 이 문구만 두고 있다.
_ANCHOR_LINE = re.compile(
    r"^(?:상품\s*)?(?:"
    r"자세히\s*보기|더\s*보기|더보기"
    r"|보러\s*가기|구경하러\s*가기"
    r"|구매하러\s*가기|바로\s*구매하기|구매하기"
    r")$"
)

# 번역·재작성 고지. `*Cosmopolitan UK 기사를 리프트 하여 작성 되었습니다. 원문 보러 가기`
# 한 줄이다. `원문 보러 가기` 가 줄 끝에 붙어 있어 앵커 규칙으로는 안 걸린다.
_NOTICE_LINE = re.compile(r"기사를\s*리프트\s*하?여?\s*작성|원문\s*보러\s*가기")

# --- 꼬리 자르기 -------------------------------------------------------------

# `|` 뒤의 출처 표기. 캡션 줄의 앞부분(브랜드·상품명)은 남긴다.
_CREDIT_TAIL = re.compile(
    r"\s*[|｜]\s*(?:출처|사진|이미지|제공|인스타그램|Instagram|Photo|Image|Courtesy)\b.*$",
    re.IGNORECASE,
)

# `Photo by Claudio Lavenia/게티 이미지` — `|` 없이 문장 끝에 붙는 촬영 크레딧.
_PHOTO_BY_TAIL = re.compile(r"\s*(?:Photo|Image)\s+by\s+.*$", re.IGNORECASE)

# `출처 게티 이미지` 처럼 구분자 없이 붙는 것. 매체가 `|` 를 빼먹은 줄이 있다.
_SOURCE_TAIL = re.compile(r"\s*출처\s*(?:게티|IMAXtree|Gettyimages)\b.*$", re.IGNORECASE)

_TAILS = (_CREDIT_TAIL, _PHOTO_BY_TAIL, _SOURCE_TAIL)


def strip_boilerplate(text: str) -> str:
    """정제된 본문 → 상투 요소를 걷은 본문. 줄 단위로 본다.

    **단계 7(공백 정규화) 뒤에 와야 한다** — 줄바꿈 하나가 남아 있고 줄 앞뒤가 트림된
    상태를 전제한다 (`text.collapse_whitespace`).

    **빈 문자열이 나올 수 있다.** 상품 링크 목록만 있던 기사가 그렇다. 그 경우 호출부가
    요약으로 떨어뜨린다 ([03 §2], `adapters/texts.build_texts`) — 여기서 판단하지 않는다.
    """
    if not text:
        return ""

    kept: list[str] = []
    for line in text.split("\n"):
        if _CUT_FROM.match(line):
            break
        if _ANCHOR_LINE.match(line) or _NOTICE_LINE.search(line):
            continue
        for tail in _TAILS:
            line = tail.sub("", line)
        line = line.strip()
        if line:
            kept.append(line)
    return "\n".join(kept)
